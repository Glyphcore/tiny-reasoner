#!/usr/bin/env python3
"""Fail on drift between spec/interfaces.py, the class boxes in spec/diagrams.md and the implementations in tr/.

Checks
1. Every class in spec/interfaces.py has a mermaid box `class <Name> {` in spec/diagrams.md with exactly the same member
   names (dataclass fields, Protocol attributes and methods), and no box exists without a spec class.
2. Every class under tr/ that lists a spec Protocol as a base defines every method of that Protocol (attributes are
   checked at runtime by tests, not here).

`--write` regenerates the boxes section of diagrams.md (between the BOXES markers) from the spec.
Exit 0 on ok, 1 on drift. Prints one line per problem, nothing on success.
"""
from __future__ import annotations

import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "spec" / "interfaces.py"
DIAG = ROOT / "spec" / "diagrams.md"
CODE = ROOT / "tr"
BEGIN, END = "<!-- BOXES BEGIN (generated by tools/spec_check.py --write) -->", "<!-- BOXES END -->"


def spec_classes() -> dict[str, dict]:
    """name -> {kind: protocol|dataclass, attrs: [name], methods: {name: signature}}"""
    tree = ast.parse(SPEC.read_text())
    out: dict[str, dict] = {}
    for node in tree.body:
        if not isinstance(node, ast.ClassDef):
            continue
        bases = [ast.unparse(b) for b in node.bases]
        kind = "protocol" if "Protocol" in bases else "dataclass"
        attrs, methods = [], {}
        for item in node.body:
            if isinstance(item, ast.AnnAssign) and isinstance(item.target, ast.Name):
                attrs.append((item.target.id, ast.unparse(item.annotation)))
            elif isinstance(item, ast.FunctionDef):
                args = [a.arg for a in item.args.args if a.arg != "self"]
                ret = ast.unparse(item.returns) if item.returns else ""
                methods[item.name] = f"({', '.join(args)}) {ret}".strip()
        out[node.name] = {"kind": kind, "attrs": attrs, "methods": methods, "bases": bases}
    return out


def render_boxes(classes: dict[str, dict]) -> str:
    lines = ["```mermaid", "classDiagram"]
    for name, c in classes.items():
        lines.append(f"  class {name} {{")
        lines.append(f"    <<{c['kind']}>>")
        for a, t in c["attrs"]:
            lines.append(f"    +{a}: {t}")
        for m, sig in c["methods"].items():
            lines.append(f"    +{m}{sig}")
        lines.append("  }")
    lines.append("```")
    return "\n".join(lines)


def diagram_boxes() -> dict[str, set[str]]:
    text = DIAG.read_text() if DIAG.exists() else ""
    boxes: dict[str, set[str]] = {}
    for m in re.finditer(r"^\s*class\s+(\w+)\s*\{(.*?)^\s*\}", text, re.S | re.M):
        members = set()
        for line in m.group(2).splitlines():
            line = line.strip().lstrip("+-#~")
            if not line or line.startswith("<<"):
                continue
            members.add(re.split(r"[:(]", line, 1)[0].strip())
        boxes[m.group(1)] = members
    return boxes


def impls() -> list[tuple[str, str, set[str]]]:
    """(file, protocol name, defined method names) for each class in tr/ that subclasses a spec Protocol."""
    found = []
    if not CODE.exists():
        return found
    for path in CODE.rglob("*.py"):
        try:
            tree = ast.parse(path.read_text())
        except SyntaxError as e:
            print(f"{path}: syntax error {e}")
            continue
        for node in ast.walk(tree):
            if isinstance(node, ast.ClassDef):
                defined = {n.name for n in node.body if isinstance(n, ast.FunctionDef)}
                for b in node.bases:
                    found.append((f"{path.relative_to(ROOT)}:{node.lineno}", ast.unparse(b).split(".")[-1], defined))
    return found


def main() -> int:
    classes = spec_classes()
    if "--write" in sys.argv:
        text = DIAG.read_text() if DIAG.exists() else f"# Spec diagrams\n\n{BEGIN}\n{END}\n"
        if BEGIN not in text:
            text += f"\n{BEGIN}\n{END}\n"
        pre, rest = text.split(BEGIN, 1)
        _, post = rest.split(END, 1)
        DIAG.write_text(f"{pre}{BEGIN}\n{render_boxes(classes)}\n{END}{post}")
        return 0

    problems = []
    boxes = diagram_boxes()
    for name, c in classes.items():
        want = {a for a, _ in c["attrs"]} | set(c["methods"])
        if name not in boxes:
            problems.append(f"diagram: missing box {name}")
        elif boxes[name] != want:
            problems.append(f"diagram: box {name} members differ: -{sorted(want - boxes[name])} +{sorted(boxes[name] - want)}")
    for name in boxes:
        if name not in classes:
            problems.append(f"diagram: box {name} has no spec class")
    protocols = {n for n, c in classes.items() if c["kind"] == "protocol"}
    for where, base, defined in impls():
        if base in protocols:
            missing = set(classes[base]["methods"]) - defined
            if missing:
                problems.append(f"{where}: {base} impl missing {sorted(missing)}")
    for p in problems:
        print(p)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
